// 生成 M3 (Material Design 3) 语义色彩 token 表 -> ui/src/services/m3-scheme.js
//
// 为什么离线生成而不是运行时算: QuickJS 20200705 跑不动 CAM16/HCT 求解器
// (hct_solver 是 300+ 行浮点迭代), 也不该让每个页面加载时付这个成本.
// 这里在构建前用 Google 官方实现 (@material/material-color-utilities 0.3.0,
// SchemeTonalSpot = Android Material You 的缺省 dynamic color 变体) 把
// 「种子色 x 明暗 x 对比度」的完整角色表算好, 运行时只做查表.
//
// 用法: node tools/gen-m3-scheme.mjs
//
// 注意: 角色清单是生成器与运行时的唯一契约 —— 顺序必须一致, theme.js 直接引用
// 这里导出的 M3_ROLES 做 zip, 不要手抄.

import { SchemeTonalSpot, MaterialDynamicColors as M, Hct, argbFromHex, hexFromArgb, Contrast } from './vendor/material-color-utilities.esm.js'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROLES = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'outline', 'outlineVariant',
  'surfaceDim', 'surfaceBright',
  'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer',
  'surfaceContainerHigh', 'surfaceContainerHighest',
  'inverseSurface', 'inverseOnSurface', 'inversePrimary'
]

// 种子色: 覆盖色环上分离良好的 8 个色相, tonal spot 的主色 chroma 固定,
// 所以决定观感差异的是色相 —— 选色时按色相拉开距离, 而不是按饱和度.
const SEEDS = [
  ['rose',   '#FB7299', '粉'],
  ['blue',   '#3D7EFF', '蓝'],
  ['teal',   '#00B3A4', '青'],
  ['green',  '#2E9E5B', '绿'],
  ['amber',  '#F2A03D', '琥珀'],
  ['violet', '#9C6BFF', '紫'],
  ['red',    '#F2544B', '红'],
  ['slate',  '#6B7280', '灰']
]

const MODES = [[false, 'light'], [true, 'dark']]
const CONTRASTS = [0, 1]

function scheme(hex, dark, contrast) {
  const s = new SchemeTonalSpot(Hct.fromInt(argbFromHex(hex)), dark, contrast)
  const out = []
  for (const r of ROLES) {
    const dc = M[r]
    if (!dc) throw new Error('unknown role ' + r)
    out.push(hexFromArgb(dc.getArgb(s)))
  }
  return out
}

// ---- 自检: M3 的可访问性契约必须成立, 不成立就不许生成产物 ----
const CONTRAST_PAIRS = [
  ['onSurface', 'surface', 4.5],
  ['onSurfaceVariant', 'surface', 4.5],
  ['onPrimary', 'primary', 4.5],
  ['onPrimaryContainer', 'primaryContainer', 4.5],
  ['onSecondaryContainer', 'secondaryContainer', 4.5],
  ['onErrorContainer', 'errorContainer', 4.5],
  ['onSurface', 'surfaceContainer', 4.5],
  ['primary', 'surface', 3.0],
  ['onSurface', 'surfaceContainerHighest', 4.5]
]

function lum(hex) {
  const n = parseInt(hex.slice(1), 16)
  const ch = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => {
    const s = v / 255
    return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4)
  })
  return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2]
}
function ratio(a, b) {
  const la = lum(a), lb = lum(b)
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05)
}

const table = {}
const problems = []
for (const [id, hex] of SEEDS) {
  for (const [dark, modeName] of MODES) {
    for (const c of CONTRASTS) {
      const vals = scheme(hex, dark, c)
      const obj = {}
      ROLES.forEach((r, i) => { obj[r] = vals[i] })
      table[id + '|' + modeName + '|' + c] = vals.join(',')
      for (const [fg, bg, min] of CONTRAST_PAIRS) {
        const got = ratio(obj[fg], obj[bg])
        if (got + 1e-9 < min) {
          problems.push(id + '|' + modeName + '|' + c + ' ' + fg + '/' + bg +
            ' = ' + got.toFixed(2) + ' < ' + min + ' (' + obj[fg] + ' on ' + obj[bg] + ')')
        }
      }
    }
  }
}

if (problems.length) {
  console.error('对比度自检失败, 不生成产物:')
  for (const p of problems) console.error('  ' + p)
  process.exit(1)
}

const lines = []
lines.push('// AUTO-GENERATED by tools/gen-m3-scheme.mjs -- 不要手改, 改生成器.')
lines.push('// 来源: @material/material-color-utilities 0.3.0, SchemeTonalSpot (Material You 缺省变体).')
lines.push('// 角色顺序 = M3_ROLES; M3_SCHEMES 的值是同序的 16 进制颜色串 (逗号分隔).')
lines.push('export const M3_ROLES = [')
lines.push(ROLES.map((r) => "  '" + r + "'").join(',\n'))
lines.push(']')
lines.push('')
lines.push('// 种子色: [id, 色值, 中文名]')
lines.push('export const M3_SEEDS = [')
lines.push(SEEDS.map((s) => "  ['" + s[0] + "', '" + s[1] + "', '" + s[2] + "']").join(',\n'))
lines.push(']')
lines.push('')
lines.push('export const M3_SCHEMES = {')
for (const k of Object.keys(table)) {
  lines.push("  '" + k + "': '" + table[k] + "',")
}
lines.push('}')
lines.push('')

const here = dirname(fileURLToPath(import.meta.url))
const outPath = join(here, '..', 'ui', 'src', 'services', 'm3-scheme.js')
writeFileSync(outPath, lines.join('\n'), 'utf8')

// 报告关键值, 便于人工核对
console.log('生成 ' + Object.keys(table).length + ' 套配色 -> ' + outPath)
for (const k of ['rose|dark|0', 'rose|light|0', 'rose|dark|1']) {
  const o = {}
  ROLES.forEach((r, i) => { o[r] = table[k].split(',')[i] })
  console.log(k + '  primary=' + o.primary + ' surface=' + o.surface +
    ' container=' + o.surfaceContainer + ' onSurface=' + o.onSurface +
    ' outline=' + o.outline)
}
